def get_main_menu():
  keyboard = []
  for key, val in AGRO_DATABASE.items():
    keyboard.append([InlineKeyboardButton(text=val["title"], callback_data=f"cat_{key}")])
  return InlineKeyboardMarkup(inline_keyboard=keyboard)


@router.message(CommandStart())
async def cmd_start(message: Message):
  text = (
      "👨‍🌾 **Приветствую, будущий агроном!**\n\n"
      "Я твой цифровой наставник по специальности **35.02.05 Агрономия**.\n"
      "Здесь собраны подробнейшие шпаргалки, научные термины, формулы и технологии для зачетов.\n\n"
      "📂 **Выбери нужный раздел ниже:**"
  )
  await message.answer(text, reply_markup=get_main_menu(), parse_mode="Markdown")


@router.callback_query(F.data.startswith("cat_"))
async def process_category(callback: CallbackQuery):
  cat_key = callback.data.split("_")[1]
  category = AGRO_DATABASE.get(cat_key)

  if not category:
    await callback.answer("Раздел не найден.")
    return

  keyboard = []
  for item_key, item_val in category["items"].items():
    keyboard.append([
        InlineKeyboardButton(
            text=item_val["name"], callback_data=f"item_{cat_key}_{item_key}"
        )
    ])
  keyboard.append([InlineKeyboardButton(text="⬅️ Назад в главное меню", callback_data="back_main")])

  await callback.message.edit_text(
      f"📂 **{category['title']}**\nВыбери конкретную тему для изучения:",
      reply_markup=InlineKeyboardMarkup(inline_keyboard=keyboard),
      parse_mode="Markdown",
  )
@router.callback_query(F.data.startswith("item_"))
async def process_item(callback: CallbackQuery):
  # Разделяем строку максимум на 2 знака подчеркивания, сохраняя ключ темы целиком
  parts = callback.data.split("_", 2)
  cat_key, item_key = parts[1], parts[2]

  # Достаем нужную информацию из базы данных
  item_data = AGRO_DATABASE.get(cat_key, {}).get("items", {}).get(item_key)

  if not item_data:
    await callback.answer("Информация не найдена.", show_alert=True)
    return

  # Кнопка возврата к списку этого же раздела
  keyboard = [[InlineKeyboardButton(text="⬅️ К списку раздела", callback_data=f"cat_{cat_key}")]]

  # Выводим подробную научную справку
  await callback.message.edit_text(
      item_data["info"],
      reply_markup=InlineKeyboardMarkup(inline_keyboard=keyboard),
      parse_mode="Markdown",
  )





@router.callback_query(F.data == "back_main")
async def process_back_main(callback: CallbackQuery):
  text = "📂 **Главное меню:**\nВыбери интересующий раздел по специальности Агрономия:"
  await callback.message.edit_text(
      text, reply_markup=get_main_menu(), parse_mode="Markdown"
  )


